export type Dict = typeof en;
export type TKey = keyof Dict;

export async function getLang(): Promise<Lang> {
  return (await cookies()).get("lang")?.value === "ml" ? "ml" : "en";
}

export async function getT() {
  const lang = await getLang();
  const d = lang === "ml" ? ml : en;
  const t = (k: TKey, vars?: Record<string, string | number>) =>
    Object.entries(vars ?? {}).reduce((s, [v, val]) => s.replace(`{${v}}`, String(val)), d[k]);
  return { t, lang, dict: d };
}

/** Pick the Malayalam field when available. */
export const pick = (lang: Lang, en: string | null | undefined, ml: string | null | undefined) =>
  (lang === "ml" && ml) || en || "";
